-- Adds fields and tables referenced by the current Node backend.

CREATE TABLE IF NOT EXISTS public.businesses (
    business_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_name VARCHAR(150) NOT NULL,
    company_type VARCHAR(80) NOT NULL,
    contact VARCHAR(40),
    email VARCHAR(255) NOT NULL UNIQUE,
    address VARCHAR(255),
    access_code_hash VARCHAR(255) NOT NULL,
    access_code_fingerprint CHAR(64) NOT NULL UNIQUE,
    status VARCHAR(10) NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'inactive')),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);


ALTER TABLE public.users
    ADD COLUMN IF NOT EXISTS email VARCHAR(255),
    ADD COLUMN IF NOT EXISTS auth_user_id UUID,
    ADD COLUMN IF NOT EXISTS business_id INTEGER;


CREATE UNIQUE INDEX IF NOT EXISTS users_auth_user_id_unique
    ON public.users(auth_user_id)
    WHERE auth_user_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS users_email_unique
    ON public.users(LOWER(email))
    WHERE email IS NOT NULL;

DO $$ BEGIN
    ALTER TABLE public.users
        ADD CONSTRAINT users_business_fk
        FOREIGN KEY (business_id) REFERENCES public.businesses(business_id);
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;


ALTER TABLE public.products
    ADD COLUMN IF NOT EXISTS business_id INTEGER;
DO $$ BEGIN
    ALTER TABLE public.products
        ADD CONSTRAINT products_business_fk
        FOREIGN KEY (business_id) REFERENCES public.businesses(business_id);
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;
CREATE INDEX IF NOT EXISTS products_business_id_idx
    ON public.products(business_id);


ALTER TABLE public.suppliers
    ADD COLUMN IF NOT EXISTS business_id INTEGER;
DO $$ BEGIN
    ALTER TABLE public.suppliers
        ADD CONSTRAINT suppliers_business_fk
        FOREIGN KEY (business_id) REFERENCES public.businesses(business_id);
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;
CREATE INDEX IF NOT EXISTS suppliers_business_id_idx
    ON public.suppliers(business_id);


CREATE TABLE IF NOT EXISTS public.inventory_history (
    history_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id INTEGER NOT NULL REFERENCES public.products(product_id),
    user_id INTEGER REFERENCES public.users(user_id),
    change_type VARCHAR(20) NOT NULL,
    quantity_before INTEGER NOT NULL,
    quantity_after INTEGER NOT NULL,
    quantity_change INTEGER NOT NULL,
    reason VARCHAR(255),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS inventory_history_product_id_idx
    ON public.inventory_history(product_id);
CREATE INDEX IF NOT EXISTS inventory_history_created_at_idx
    ON public.inventory_history(created_at DESC);
