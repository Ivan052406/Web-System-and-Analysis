-- CASIA migration 003: multi-branch inventory, sales, reports and staff access.
-- Run ONCE after migrations 001 and 002. Back up the Supabase database first.
-- Existing rows are assigned to a default "Main Branch"; their quantities are
-- moved, not duplicated. New branches start with zero stock per product.

CREATE TABLE IF NOT EXISTS public.branches (
    branch_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT NOT NULL REFERENCES public.businesses(business_id) ON DELETE CASCADE,
    branch_name VARCHAR(150) NOT NULL,
    address TEXT,
    contact VARCHAR(40),
    status VARCHAR(10) NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT branches_business_name_unique UNIQUE (business_id, branch_name)
);
CREATE INDEX IF NOT EXISTS branches_business_status_idx
    ON public.branches(business_id, status);

-- Keep the existing business registration access code as the staff shared
-- access code as requested. Admin login still requires email + password + code.

INSERT INTO public.branches (business_id, branch_name, status)
SELECT b.business_id, 'Main Branch', 'active'
FROM public.businesses b
WHERE NOT EXISTS (
    SELECT 1 FROM public.branches br WHERE br.business_id = b.business_id
)
ON CONFLICT (business_id, branch_name) DO NOTHING;

ALTER TABLE public.inventory ADD COLUMN IF NOT EXISTS branch_id BIGINT;
ALTER TABLE public.sales ADD COLUMN IF NOT EXISTS branch_id BIGINT;
ALTER TABLE public.restocks ADD COLUMN IF NOT EXISTS branch_id BIGINT;
ALTER TABLE public.inventory_history ADD COLUMN IF NOT EXISTS branch_id BIGINT;

-- Move existing inventory/sales/restocks/history to each business's Main Branch.
UPDATE public.inventory i
SET branch_id = br.branch_id
FROM public.products p
JOIN public.branches br ON br.business_id = p.business_id
WHERE p.product_id = i.product_id
  AND i.branch_id IS NULL;

UPDATE public.sales s
SET branch_id = br.branch_id
FROM public.users u
JOIN public.branches br ON br.business_id = u.business_id
WHERE u.user_id = s.user_id
  AND s.branch_id IS NULL;

-- If a legacy sale was recorded under a user profile without business_id,
-- infer its business from the products on that sale when all items belong to
-- exactly one business. Ambiguous cross-business sales are intentionally not
-- assigned automatically.
UPDATE public.sales s
SET branch_id = br.branch_id
FROM (
    SELECT si.sale_id, MIN(p.business_id) AS business_id
    FROM public.sale_items si
    JOIN public.products p ON p.product_id = si.product_id
    GROUP BY si.sale_id
    HAVING COUNT(DISTINCT p.business_id) = 1
) sale_business
JOIN public.branches br ON br.business_id = sale_business.business_id
WHERE s.sale_id = sale_business.sale_id
  AND s.branch_id IS NULL;

UPDATE public.restocks r
SET branch_id = br.branch_id
FROM public.products p
JOIN public.branches br ON br.business_id = p.business_id
WHERE p.product_id = r.product_id
  AND r.branch_id IS NULL;

UPDATE public.inventory_history h
SET branch_id = br.branch_id
FROM public.products p
JOIN public.branches br ON br.business_id = p.business_id
WHERE p.product_id = h.product_id
  AND h.branch_id IS NULL;

-- Stop before adding constraints if a legacy record could not be mapped.
DO $$
DECLARE
    missing_inventory BIGINT;
    missing_sales BIGINT;
    missing_restocks BIGINT;
    missing_history BIGINT;
BEGIN
    SELECT COUNT(*) INTO missing_inventory FROM public.inventory WHERE branch_id IS NULL;
    SELECT COUNT(*) INTO missing_sales FROM public.sales WHERE branch_id IS NULL;
    SELECT COUNT(*) INTO missing_restocks FROM public.restocks WHERE branch_id IS NULL;
    SELECT COUNT(*) INTO missing_history FROM public.inventory_history WHERE branch_id IS NULL;
    IF missing_inventory + missing_sales + missing_restocks + missing_history > 0 THEN
        RAISE EXCEPTION 'CASIA branch migration could not assign all old records. Unassigned rows: inventory %, sales %, restocks %, inventory_history %. Review each record and set branch_id to its correct Main Branch before rerunning migration 003.',
            missing_inventory, missing_sales, missing_restocks, missing_history;
    END IF;
END $$;

-- Remove the old UNIQUE(product_id) rule so each product can have one stock
-- row per branch. Preserve the product foreign key.
DO $$
DECLARE c RECORD;
BEGIN
    FOR c IN
        SELECT con.conname
        FROM pg_constraint con
        WHERE con.conrelid = 'public.inventory'::regclass
          AND con.contype = 'u'
          AND (
            SELECT array_agg(att.attname ORDER BY att.attname)
            FROM unnest(con.conkey) AS key(attnum)
            JOIN pg_attribute att
              ON att.attrelid = con.conrelid AND att.attnum = key.attnum
          ) = ARRAY['product_id']::name[]
    LOOP
        EXECUTE format('ALTER TABLE public.inventory DROP CONSTRAINT %I', c.conname);
    END LOOP;
END $$;

ALTER TABLE public.inventory ALTER COLUMN branch_id SET NOT NULL;
ALTER TABLE public.sales ALTER COLUMN branch_id SET NOT NULL;
ALTER TABLE public.restocks ALTER COLUMN branch_id SET NOT NULL;
ALTER TABLE public.inventory_history ALTER COLUMN branch_id SET NOT NULL;

DO $$ BEGIN
    ALTER TABLE public.inventory
        ADD CONSTRAINT inventory_branch_fk
        FOREIGN KEY (branch_id) REFERENCES public.branches(branch_id);
EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$ BEGIN
    ALTER TABLE public.sales
        ADD CONSTRAINT sales_branch_fk
        FOREIGN KEY (branch_id) REFERENCES public.branches(branch_id);
EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$ BEGIN
    ALTER TABLE public.restocks
        ADD CONSTRAINT restocks_branch_fk
        FOREIGN KEY (branch_id) REFERENCES public.branches(branch_id);
EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$ BEGIN
    ALTER TABLE public.inventory_history
        ADD CONSTRAINT inventory_history_branch_fk
        FOREIGN KEY (branch_id) REFERENCES public.branches(branch_id);
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

CREATE UNIQUE INDEX IF NOT EXISTS inventory_branch_product_unique
    ON public.inventory(branch_id, product_id);
CREATE INDEX IF NOT EXISTS sales_branch_date_idx
    ON public.sales(branch_id, sale_date DESC);
CREATE INDEX IF NOT EXISTS restocks_branch_date_idx
    ON public.restocks(branch_id, restock_date DESC);
CREATE INDEX IF NOT EXISTS inventory_history_branch_created_idx
    ON public.inventory_history(branch_id, created_at DESC);

-- Create zero-stock rows for any existing active products/branches that do
-- not already have an inventory row. This does NOT copy existing stock.
INSERT INTO public.inventory (branch_id, product_id, quantity)
SELECT br.branch_id, p.product_id, 0
FROM public.products p
JOIN public.branches br ON br.business_id = p.business_id
WHERE NOT EXISTS (
    SELECT 1 FROM public.inventory i
    WHERE i.branch_id = br.branch_id AND i.product_id = p.product_id
)
ON CONFLICT (branch_id, product_id) DO NOTHING;

-- Shared cashier identity per business. It is an internal sales attribution
-- record, not a login account; staff access is via the business access code.
INSERT INTO public.users (name, username, password, role, status, email, business_id)
SELECT 'Shared Cashier', 'shared-cashier-' || b.business_id, NULL, 'staff', 'active', NULL, b.business_id
FROM public.businesses b
WHERE NOT EXISTS (
    SELECT 1 FROM public.users u
    WHERE u.username = 'shared-cashier-' || b.business_id
)
ON CONFLICT (username) DO NOTHING;

CREATE TABLE IF NOT EXISTS public.staff_access_sessions (
    session_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash CHAR(64) NOT NULL UNIQUE,
    business_id BIGINT NOT NULL REFERENCES public.businesses(business_id) ON DELETE CASCADE,
    branch_id BIGINT NOT NULL REFERENCES public.branches(branch_id) ON DELETE CASCADE,
    cashier_user_id INTEGER NOT NULL REFERENCES public.users(user_id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS staff_access_sessions_expiry_idx
    ON public.staff_access_sessions(expires_at)
    WHERE revoked_at IS NULL;

