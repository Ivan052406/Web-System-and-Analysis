CREATE TABLE public.categories (
    category_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(50) NOT NULL UNIQUE
);


CREATE TABLE public.users (
    user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    username VARCHAR(50) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(10) NOT NULL CHECK (role IN ('admin', 'staff')),
    status VARCHAR(10) NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'inactive')),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);


CREATE TABLE public.suppliers (
    supplier_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_name VARCHAR(100) NOT NULL,
    contact_number VARCHAR(30),
    address VARCHAR(255),
    status VARCHAR(10) NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'inactive'))
);


CREATE TABLE public.products (
    product_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id INTEGER NOT NULL,
    product_name VARCHAR(100) NOT NULL,
    price NUMERIC(10,2) NOT NULL,
    minimum_stock INTEGER NOT NULL DEFAULT 0,
    status VARCHAR(10) NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'inactive')),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT products_category_fk
        FOREIGN KEY (category_id)
        REFERENCES public.categories(category_id)
);


CREATE TABLE public.inventory (
    inventory_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id INTEGER NOT NULL UNIQUE,
    quantity INTEGER NOT NULL DEFAULT 0,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT inventory_product_fk
        FOREIGN KEY (product_id)
        REFERENCES public.products(product_id)
);


CREATE TABLE public.sales (
    sale_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    total_amount NUMERIC(10,2) NOT NULL,
    sale_date DATE NOT NULL,
    sale_time TIME NOT NULL,

    CONSTRAINT sales_user_fk
        FOREIGN KEY (user_id)
        REFERENCES public.users(user_id)
);


CREATE TABLE public.restocks (
    restock_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id INTEGER NOT NULL,
    product_id INTEGER NOT NULL,
    quantity INTEGER NOT NULL,
    restock_date DATE NOT NULL,
    restock_time TIME NOT NULL,
    user_id INTEGER NOT NULL,

    CONSTRAINT restocks_supplier_fk
        FOREIGN KEY (supplier_id)
        REFERENCES public.suppliers(supplier_id),

    CONSTRAINT restocks_product_fk
        FOREIGN KEY (product_id)
        REFERENCES public.products(product_id),

    CONSTRAINT restocks_user_fk
        FOREIGN KEY (user_id)
        REFERENCES public.users(user_id)
);


CREATE TABLE public.sale_items (
    sale_item_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id INTEGER NOT NULL,
    product_id INTEGER NOT NULL,
    quantity INTEGER NOT NULL,
    unit_price NUMERIC(10,2) NOT NULL,
    subtotal NUMERIC(10,2) NOT NULL,

    CONSTRAINT sale_items_sale_fk
        FOREIGN KEY (sale_id)
        REFERENCES public.sales(sale_id),

    CONSTRAINT sale_items_product_fk
        FOREIGN KEY (product_id)
        REFERENCES public.products(product_id)
);



